-- 1. Eliminar la tabla si ya existe
DROP TABLE IF EXISTS libros CASCADE CONSTRAINTS;

-- 2. Tabla mapeada a la entidad com.duoc.gestor_biblioteca.model.Libro
--    Los largos son mayores o iguales a los limites de LibroRequest
--    (titulo 150, autor 100, genero 100), asi la API rechaza con 400
--    antes de que Oracle tenga que rechazar con un error.
CREATE TABLE libros (
    id                NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    titulo            VARCHAR2(255) NOT NULL,
    autor             VARCHAR2(255) NOT NULL,
    anio_publicacion  NUMBER(4)     NOT NULL,
    genero            VARCHAR2(255) NOT NULL
);

